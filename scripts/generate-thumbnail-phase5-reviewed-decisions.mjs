import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalizeProductCodeValue } from "../src/lib/fanza/normalize.ts";
import { adaptHumanApprovalRecord } from "../src/lib/thumbnail/adapters.ts";
import { isTrustedThumbnailOutput } from "../src/lib/thumbnail/contract.ts";
import {
  parseCsv,
  writeFileAtomically,
} from "./generate-thumbnail-production-registry.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(root, "data", "thumbnail-phase5-reviewed-decisions.csv");
const generatedPath = path.join(
  root,
  "src",
  "lib",
  "thumbnail",
  "generated-phase5-reviewed-decisions.ts",
);
const SHA256 = /^[a-f0-9]{64}$/;
const SOURCE_IDS = Object.freeze({
  SAMPLE: /^sample:[1-9]\d*$/,
  PACKAGE_RIGHT: /^dvd:right$/,
  PACKAGE_CENTER: /^dvd:center$/,
  PACKAGE_FULL: /^dvd:full$/,
});
const EXPECTED_HEADERS = Object.freeze([
  "code",
  "mode",
  "source_id",
  "source_path_or_url",
  "source_hash",
  "output_path_or_url",
  "output_hash",
  "approved_by",
  "approved_at",
  "approval_batch",
  "reason",
  "apply",
  "review_status",
]);

const sha256 = (value) => crypto.createHash("sha256").update(value).digest("hex");
const required = (value, context) => {
  const normalized = String(value ?? "").trim();
  if (!normalized) throw new Error(`${context}:MISSING_VALUE`);
  return normalized;
};

function canonicalCode(value) {
  const raw = required(value, "PHASE5_REVIEWED:CODE");
  const result = canonicalizeProductCodeValue(raw);
  if (!result.canonical || result.rejected || result.canonical !== raw) {
    throw new Error(`PHASE5_REVIEWED:INVALID_CANONICAL_CODE:${raw}`);
  }
  return raw;
}

async function verifyOutput(code, mode, sourcePath, sourceHash, outputPath, outputHash) {
  if (mode === "SAMPLE" || mode === "PACKAGE_FULL") {
    if (sourcePath !== outputPath || sourceHash !== outputHash) {
      throw new Error(`PHASE5_REVIEWED:${code}:UNEXPECTED_TRANSFORM`);
    }
    return;
  }
  if (!outputPath.startsWith("/card-thumbnails/")) {
    throw new Error(`PHASE5_REVIEWED:${code}:CROP_OUTPUT_MUST_BE_LOCAL`);
  }
  const relative = `public${outputPath}`;
  if (path.posix.normalize(relative) !== relative || relative.split("/").includes("..")) {
    throw new Error(`PHASE5_REVIEWED:${code}:INVALID_OUTPUT_PATH`);
  }
  const absolute = path.resolve(root, relative);
  const publicRoot = path.resolve(root, "public", "card-thumbnails");
  if (!absolute.startsWith(`${publicRoot}${path.sep}`)) {
    throw new Error(`PHASE5_REVIEWED:${code}:OUTPUT_PATH_ESCAPE`);
  }
  const info = await fs.lstat(absolute);
  if (!info.isFile() || info.isSymbolicLink()) {
    throw new Error(`PHASE5_REVIEWED:${code}:OUTPUT_NOT_REGULAR_FILE`);
  }
  const bytes = await fs.readFile(absolute);
  if (!bytes.length || sha256(bytes) !== outputHash) {
    throw new Error(`PHASE5_REVIEWED:${code}:OUTPUT_HASH_MISMATCH`);
  }
}

async function materialize(row) {
  const code = canonicalCode(row.code);
  const context = `PHASE5_REVIEWED:${code}`;
  const mode = required(row.mode, `${context}:MODE`);
  const sourceId = required(row.source_id, `${context}:SOURCE_ID`);
  const sourcePath = required(row.source_path_or_url, `${context}:SOURCE_PATH`);
  const outputPath = required(row.output_path_or_url, `${context}:OUTPUT_PATH`);
  const sourceHash = required(row.source_hash, `${context}:SOURCE_HASH`).toLowerCase();
  const outputHash = required(row.output_hash, `${context}:OUTPUT_HASH`).toLowerCase();
  if (!SOURCE_IDS[mode]?.test(sourceId)) throw new Error(`${context}:SOURCE_ID_CONTRACT`);
  if (!SHA256.test(sourceHash) || !SHA256.test(outputHash)) throw new Error(`${context}:HASH_CONTRACT`);
  if (!isTrustedThumbnailOutput(sourcePath) || !isTrustedThumbnailOutput(outputPath)) {
    throw new Error(`${context}:URL_CONTRACT`);
  }
  if (row.review_status !== "HUMAN_APPROVED") {
    throw new Error(`${context}:REVIEW_STATUS_CONTRACT`);
  }
  await verifyOutput(code, mode, sourcePath, sourceHash, outputPath, outputHash);
  const record = {
    code,
    mode,
    state: "RESOLVED",
    source_id: sourceId,
    source_path_or_url: sourcePath,
    source_hash: sourceHash,
    output_path_or_url: outputPath,
    output_hash: outputHash,
    crop_spec: null,
    approved_by: required(row.approved_by, `${context}:APPROVED_BY`),
    approved_at: required(row.approved_at, `${context}:APPROVED_AT`),
    approval_batch: required(row.approval_batch, `${context}:APPROVAL_BATCH`),
    reason: required(row.reason, `${context}:REASON`),
  };
  adaptHumanApprovalRecord(record);
  return record;
}

function stableSource({ records, inputHash, stats }) {
  return `/* This file is generated by scripts/generate-thumbnail-phase5-reviewed-decisions.mjs. */
/* Do not edit it by hand. It is static and safe for client bundles. */

import type { CanonicalDecisionRecord } from "./adapters.ts";

export const GENERATED_PHASE5_REVIEWED_DECISION_RECORDS = Object.freeze(
  ${JSON.stringify(records, null, 2)} as const satisfies readonly CanonicalDecisionRecord[],
);

export const GENERATED_PHASE5_REVIEWED_STATS = Object.freeze(
  ${JSON.stringify(stats, null, 2)} as const,
);

export const GENERATED_PHASE5_REVIEWED_INPUT_SHA256 = ${JSON.stringify(inputHash)};
`;
}

export async function generatePhase5ReviewedSource({ decisionFilePath = inputPath } = {}) {
  const input = await fs.readFile(decisionFilePath, "utf8");
  const header = input.slice(0, input.indexOf("\n")).replace(/\r$/, "").split(",");
  if (JSON.stringify(header) !== JSON.stringify(EXPECTED_HEADERS)) {
    throw new Error("PHASE5_REVIEWED:INVALID_HEADERS");
  }
  const rows = parseCsv(input);
  const eligibleRows = rows.filter((row) => row.apply === "true");
  const records = (await Promise.all(eligibleRows.map(materialize))).sort((left, right) =>
    left.code.localeCompare(right.code, "en"));
  const seen = new Set();
  for (const record of records) {
    if (seen.has(record.code)) throw new Error(`PHASE5_REVIEWED:DUPLICATE_CODE:${record.code}`);
    seen.add(record.code);
  }
  const stats = {
    input_total: rows.length,
    eligible_total: records.length,
    ignored_apply_false: rows.length - eligibleRows.length,
  };
  return {
    records,
    inputHash: sha256(input),
    stats,
    source: stableSource({ records, inputHash: sha256(input), stats }),
  };
}

export async function runCli(args = process.argv.slice(2)) {
  const result = await generatePhase5ReviewedSource();
  if (args.includes("--write")) {
    await writeFileAtomically(generatedPath, result.source);
  } else if (args.includes("--check")) {
    const existing = await fs.readFile(generatedPath, "utf8");
    if (existing !== result.source) throw new Error("PHASE5_REVIEWED_REGISTRY_OUT_OF_SYNC");
  } else {
    process.stdout.write(result.source);
  }
  process.stderr.write(`${JSON.stringify(result.stats)}\n`);
}

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) await runCli();
